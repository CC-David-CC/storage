import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createTemporaryFiles} from '../active-system/storage/browser/temporary-files.mjs';

test('a guest home belongs to one live session and enforces exact file revisions', async () => {
  let active = true;
  const guest = createTemporaryFiles(() => active);
  const other = createTemporaryFiles(() => true);
  const path = 'Documents/example.txt';
  const {files} = guest;
  const first = await files.write(path, new Uint8Array([1]));
  assert.equal((await other.files.list('Documents')).entries.length, 0);
  const races = await Promise.allSettled([2,3].map(value => files.write(path,new Uint8Array([value]),first.sha256)));
  assert.equal(races.filter(result=>result.status==='fulfilled').length,1);
  assert.equal(races.find(result=>result.status==='rejected').reason.status,409);
  const saved = await files.read(path);
  saved.data.fill(0);
  assert.notEqual((await files.read(path)).data[0],0);
  const thaw = guest.freeze();
  await assert.rejects(files.remove(path,saved.sha256),{status:409});
  assert.equal((await files.read(path)).sha256,saved.sha256);
  thaw();
  await assert.rejects(files.rename(path,'../name',saved.sha256));
  await files.rename(path,'Documents/renamed.txt',saved.sha256);
  await assert.rejects(files.remove('Documents'),{status:409});
  active=false;
  await assert.rejects(files.list('Documents'),{name:'AbortError'});
});

test('legacy editors see, change and subscribe to the same temporary Files tree', async () => {
  let valid = true;
  const {files, mirror, freeze} = createTemporaryFiles(() => valid);
  const path = '/Documents/shared.txt';
  const relative = path.slice(1);
  let changes = 0;
  const unsubscribe = mirror.subscribe(() => ++changes);
  await assert.rejects(mirror.stat(path), {status:404, message:'File not found.'});
  const first = await files.write(relative, 'local');
  assert.equal(changes, 1);
  const [row] = (await mirror.list('/Documents')).entries;
  assert.equal(row.path, path);
  assert.equal(row.version, first.sha256);
  const selected = await mirror.stat(path);
  assert.equal(selected.bytes, 5);
  const lease = await mirror.acquireSnapshot(path, {expected:selected.version});
  const next = await mirror.write(path, new Blob(['edited']), selected.version);
  assert.equal((await files.version(relative)).sha256, next.version);
  assert.equal(await lease.data.text(), 'local');
  lease.release();
  await assert.rejects(mirror.acquireSnapshot(path, {expected:selected.version}), {name:'MirrorConflict'});
  await assert.rejects(mirror.write(path, 'stale', selected.version), {name:'MirrorConflict'});
  await assert.rejects(mirror.readBounded(path, 2), /exceeds/);
  const controller = new AbortController();
  controller.abort();
  await assert.rejects(mirror.acquireSnapshot(path,{signal:controller.signal}), {name:'AbortError'});
  const thaw = freeze();
  await assert.rejects(mirror.write(path, 'frozen', next.version));
  thaw();
  assert.equal(changes, 2);
  const races = await Promise.allSettled(['a','b'].map(text => mirror.write(path,text,next.version)));
  assert.equal(races.filter(r=>r.status==='fulfilled').length, 1);
  assert.equal(races.find(r=>r.status==='rejected').reason.name, 'MirrorConflict');
  unsubscribe();
  const latest = await files.version(relative);
  await files.rename(relative, 'Documents/new-name.txt', latest.sha256);
  assert.equal(changes, 3);
  assert.equal((await mirror.list('/Documents')).entries[0].name, 'new-name.txt');
  await assert.rejects(createTemporaryFiles(()=>true).mirror.stat('/Documents/new-name.txt'), {status:404});
  valid = false;
  await assert.rejects(mirror.stat('/Documents/new-name.txt'), {name:'AbortError'});
  await assert.rejects(mirror.list(), {name:'AbortError'});
});
